'use strict';

/* ==========================================================================
   Banco de dados: Postgres no Neon, o mesmo para o painel deste PC e para a
   página de consulta na Vercel. O driver fala com o Neon por HTTP, então cada
   consulta é uma requisição — sem conexão aberta para cair.

   A connection string vem de DATABASE_URL. Neste PC ela fica no arquivo .env
   (fora do git e do deploy); na Vercel, nas variáveis de ambiente do projeto.
   ========================================================================== */

const path = require('node:path');
const { neon } = require('@neondatabase/serverless');

const CAMINHO_ENV = path.join(__dirname, '.env');

if (!process.env.DATABASE_URL) {
  try {
    process.loadEnvFile(CAMINHO_ENV);
  } catch { /* sem .env: na Vercel a variável já vem do ambiente */ }
}

/** Sem internet (ou Neon fora do ar): nada foi gravado. */
class ErroBanco extends Error {
  constructor(causa) {
    super('Sem conexão com o banco de dados na nuvem.');
    this.codigo = 'banco_fora_do_ar';
    this.cause = causa;
  }
}

let sqlCache = null;
function sql() {
  if (sqlCache) return sqlCache;
  const url = process.env.DATABASE_URL;
  if (!url) {
    throw new Error(`Falta DATABASE_URL. Crie o arquivo ${CAMINHO_ENV} com DATABASE_URL=postgresql://...`);
  }
  sqlCache = neon(url);
  return sqlCache;
}

/**
 * Toda consulta passa por aqui. Erro que o Postgres devolveu tem `code`
 * (SQLSTATE) e é bug ou regra do banco; erro sem `code` é a requisição que
 * nem chegou lá — vira ErroBanco para a tela mostrar "sem internet".
 */
async function consultar(texto, params = []) {
  try {
    return await sql().query(texto, params);
  } catch (e) {
    if (e && e.code) throw e;
    throw new ErroBanco(e);
  }
}

/**
 * Cria as tabelas na primeira vez. O servidor deste PC roda isso ao subir;
 * a consulta na Vercel só lê e não mexe no esquema.
 *
 * `id` é integer (e não bigint) de propósito: bigint chega no JavaScript
 * como texto, e a tela compara e devolve os ids como número.
 */
async function garantirEsquema() {
  await consultar(`
    CREATE TABLE IF NOT EXISTS itens (
      id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      codigo     text NOT NULL,
      entrada_em timestamptz NOT NULL DEFAULT now()
    )`);
  // Um código aparece uma vez só: o banco impede entrada duplicada de um item
  // que já está guardado, sem depender de checagem na aplicação.
  await consultar('CREATE UNIQUE INDEX IF NOT EXISTS idx_codigo ON itens (codigo)');
  await consultar('CREATE INDEX IF NOT EXISTS idx_entrada_em ON itens (entrada_em)');
  await consultar(`
    CREATE TABLE IF NOT EXISTS tally_confirmacoes (
      digitado      text PRIMARY KEY,
      codigo        text NOT NULL,
      confirmado_em timestamptz NOT NULL DEFAULT now()
    )`);
  await consultar(`
    CREATE TABLE IF NOT EXISTS tally_resolvidos (
      digitado     text PRIMARY KEY,
      observacao   text NOT NULL,
      resolvido_em timestamptz NOT NULL DEFAULT now()
    )`);
}

// Datas saem como texto ISO em UTC (…T12:00:00.000Z), o mesmo formato que o
// SQLite guardava — a tela não precisa saber que o banco mudou.
const ITEM = `id, codigo, to_char(entrada_em AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') AS entrada_em`;

/**
 * Registra a entrada de um item. Falha se o código já estiver guardado.
 */
async function registrarEntrada(codigo) {
  const [novo] = await consultar(
    `INSERT INTO itens (codigo, entrada_em) VALUES ($1, now())
     ON CONFLICT (codigo) DO NOTHING
     RETURNING ${ITEM}`,
    [codigo]
  );
  if (novo) return { ok: true, acao: 'entrada', item: novo };

  // O índice único barrou: já estava guardado (ou outra aba gravou agora).
  const [existente] = await consultar(`SELECT ${ITEM} FROM itens WHERE codigo = $1`, [codigo]);
  return { ok: false, erro: 'ja_guardado', item: existente };
}

/**
 * Remove a linha de um item. Serve tanto ao desfazer da última leitura quanto
 * ao apagar avulso pela lista: nos dois casos o registro simplesmente sai.
 */
async function removerPorId(id) {
  const [item] = await consultar(`DELETE FROM itens WHERE id = $1 RETURNING ${ITEM}`, [id]);
  if (!item) return { ok: false, erro: 'nao_encontrado' };
  return { ok: true, item };
}

/**
 * Lista itens com busca por código, do mais recente para o mais antigo.
 * ILIKE para ignorar maiúsculas/minúsculas, como fazia o LIKE do SQLite.
 */
async function listar({ q = '', limite = 500, offset = 0 } = {}) {
  const busca = String(q).trim();
  const clausula = busca ? 'WHERE codigo ILIKE $1' : '';
  const params = busca ? [`%${busca}%`] : [];
  const n = params.length;

  const [itens, [{ filtrados }], guardados] = await Promise.all([
    consultar(
      `SELECT ${ITEM}
         FROM itens
         ${clausula}
        ORDER BY entrada_em DESC, id DESC
        LIMIT $${n + 1} OFFSET $${n + 2}`,
      [...params, limite, offset]
    ),
    consultar(`SELECT COUNT(*)::int AS filtrados FROM itens ${clausula}`, params),
    contadores(),
  ]);

  return { itens, filtrados, ...guardados };
}

async function contadores() {
  const [{ guardados }] = await consultar('SELECT COUNT(*)::int AS guardados FROM itens');
  return { guardados };
}

/**
 * Fotografia do estoque: um registro por código.
 * Usado pelas conferências para cruzar com a planilha do PBI e com o Tally.
 */
async function todosOsCodigos() {
  const linhas = await consultar(`SELECT ${ITEM} FROM itens`);
  return linhas.map(({ codigo, entrada_em }) => ({ codigo, entrada_em }));
}

/**
 * Entradas bipadas no intervalo [inicio, fim), recebido em ISO.
 * Usado para conferir com os formulários do Tally.
 */
async function entradasNoPeriodo(inicio, fim) {
  return consultar(
    `SELECT ${ITEM}
       FROM itens
      WHERE entrada_em >= $1 AND entrada_em < $2
      ORDER BY entrada_em`,
    [inicio, fim]
  );
}

module.exports = {
  ErroBanco,
  consultar,
  garantirEsquema,
  entradasNoPeriodo,
  registrarEntrada,
  removerPorId,
  listar,
  contadores,
  todosOsCodigos,
};
